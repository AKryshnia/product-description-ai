@pytest.mark.parametrize(
    ("name", "text", "what", "code"), DISTORTED, ids=[f"{t} [{w}]" for _, t, w, _ in DISTORTED]
)
def test_distortion_is_reported_with_its_reason(name, text, what, code):
    assert code in {i.code for i in findings(name, text)}
